    /**
     * Upload import file via AJAX
     *
     * @return void
     *
     * @throws \Exception
     * @since 10.1.0
     */
    public function uploadImportFileXHR(): void
    {
        // Check for request forgeries
        if (!Session::checkToken('get') && !Session::checkToken()) {
            $this->sendJsonResponse(false, Text::_('JINVALID_TOKEN'));
        }

        $app      = Factory::getApplication();
        $input    = $app->getInput();
        $userfile = $input->files->get('importdb', null, 'raw');

        if (!\is_array($userfile) || $userfile['error'] || $userfile['size'] < 1) {
            $this->sendJsonResponse(false, Text::_('JBS_IBM_ERROR_UPLOAD_FAILED'));
        }

        // Move uploaded file to tmp
        $config   = $app->getConfig();
        $tmpPath  = $config->get('tmp_path') . '/' . $userfile['name'];

        if (!File::upload($userfile['tmp_name'], $tmpPath, false, true)) {
            $this->sendJsonResponse(false, 'Failed to move uploaded file');
        }

        // Handle ZIP files
        if (str_ends_with(strtolower($tmpPath), '.zip')) {
            $package = InstallerHelper::unpack($tmpPath, true);

            if (!isset($package['dir'])) {
                $this->sendJsonResponse(false, 'Failed to extract ZIP file');
            }

            // Find SQL file in extracted directory
            $files = Folder::files($package['dir'], '\.sql$', true, true);

            if (empty($files)) {
                $this->sendJsonResponse(false, 'No SQL file found in archive');
            }

            $tmpPath = $files[0];
        }

        // Generate session ID and store a file path
        $sessionId = md5(uniqid((string) mt_rand(), true));
        $session   = $app->getSession();
        $session->set('proclaim_import_' . $sessionId, $tmpPath, 'CWM');

        $this->sendJsonResponse(true, '', ['sessionId' => $sessionId]);
    }

    /**
     * Prepare import from backup folder or tmp folder
     *
     * @return void
     *
     * @throws \Exception
     * @since 10.1.0
     */
    public function prepareImportXHR(): void
    {
        // Check for request forgeries
        if (!Session::checkToken('get') && !Session::checkToken()) {
            $this->sendJsonResponse(false, Text::_('JINVALID_TOKEN'));
        }

        $app    = Factory::getApplication();
        $input  = $app->getInput();
        $type   = $input->get('type', '', 'string');
        $source = $input->get('source', '', 'string');

        if (empty($type) || empty($source)) {
            $this->sendJsonResponse(false, 'Missing type or source parameter');
        }

        $filePath = '';

        if ($type === 'backup') {
            // From backup folder
            $filePath = JPATH_SITE . '/media/com_proclaim/backup/' . basename($source);
        } elseif ($type === 'folder') {
            // From tmp folder
            $filePath = Path::clean($source);
        }

        if (!is_file($filePath)) {
            $this->sendJsonResponse(false, Text::_('JBS_IBM_NOT_DB'));
        }

        // Generate session ID and store a file path
        $sessionId = md5(uniqid((string) mt_rand(), true));
        $session   = $app->getSession();
        $session->set('proclaim_import_' . $sessionId, $filePath, 'CWM');

        $this->sendJsonResponse(true, '', ['sessionId' => $sessionId]);
    }

    /**
     * Get import file info (for progress tracking)
     *
     * @return void
     *
     * @throws \Exception
     * @since 10.1.0
     */
    public function getImportInfoXHR(): void
    {
        // Check for request forgeries
        if (!Session::checkToken('get') && !Session::checkToken()) {
            $this->sendJsonResponse(false, Text::_('JINVALID_TOKEN'));
        }

        $app       = Factory::getApplication();
        $input     = $app->getInput();
        $sessionId = $input->get('sessionId', '', 'string');
        $session   = $app->getSession();

        $filePath = $session->get('proclaim_import_' . $sessionId, '', 'CWM');

        if (empty($filePath) || !is_file($filePath)) {
            $this->sendJsonResponse(false, 'Import file not found');
        }

        // Read and validate a file
        $content = file_get_contents($filePath);

        if ($content === false) {
            $this->sendJsonResponse(false, Text::_('JBS_INS_ERROR_SQL_READBUFFER'));
        }

        // Validate it's a Proclaim backup
        $isnot = substr_count($content, '#__bsms_studies');

        if ($isnot === 0) {
            $this->sendJsonResponse(false, Text::_('JBS_IBM_NOT_DB'));
        }

        // Splitting is the one step whose cost is the size of the whole file,
        // and it is measured in seconds per megabyte. The browser is told to
        // wait; PHP has to be told as well, or a large dump dies here on a
        // default 30- or 60-second limit.
        if (\function_exists('set_time_limit')) {
            @set_time_limit(600);
        }

        // A dump written by anything other than Cwmbackup lists generated
        // columns like any other, and MySQL rejects every INSERT that names
        // one. Rewrite them before the split so the demoted definitions and
        // the statements that put them back travel together.
        $normalised = Cwmrestore::normaliseGeneratedColumns($content);

        // Split into queries. Cwmrestore::splitSqlFast() is a port of the core
        // splitter that returns the same statements without allocating four
        // short strings per character; see its docblock.
        $queries = Cwmrestore::splitSqlFast($normalised['sql']);

        // The generated columns go back on once every row is loaded.
        foreach ($normalised['restore'] as $restore) {
            $queries[] = $restore;
        }

        // Spool the statements to disk, one JSON-encoded statement per line.
        //
        // ⚠️ These used to go in the session. #__session.data is a mediumtext,
        // and writing a row that size also needs max_allowed_packet above it,
        // so a dump of any real size failed the session write silently — after
        // this method had already told the browser how many batches to expect.
        // The next request found nothing and reported "No queries found in
        // session". JSON encoding is what makes the line-per-statement format
        // safe: it escapes the newlines inside a statement.
        $this->sweepStaleSpools();

        $spoolPath = $this->importSpoolPath($sessionId);
        $spool     = fopen($spoolPath, 'wb');

        if ($spool === false) {
            $this->sendJsonResponse(false, Text::_('JBS_IBM_SPOOL_FAILED'));
        }

        foreach ($queries as $query) {
            fwrite($spool, json_encode($query, JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR) . "\n");
        }

        fclose($spool);

        // Only the count and the path go in the session now.
        $session->set('proclaim_import_count_' . $sessionId, \count($queries), 'CWM');

        $totalBatches = (int) ceil(\count($queries) / self::IMPORT_BATCH_SIZE);

        $this->sendJsonResponse(true, '', [
            'totalQueries' => \count($queries),
            'totalBatches' => $totalBatches,
            'batchSize'    => self::IMPORT_BATCH_SIZE,
        ]);
    }

    /**
     * Import a batch of SQL queries
     *
     * @return void
     *
     * @throws \Exception
     * @since 10.1.0
     */
    public function importBatchXHR(): void
    {
        // Check for request forgeries
        if (!Session::checkToken('get') && !Session::checkToken()) {
            $this->sendJsonResponse(false, Text::_('JINVALID_TOKEN'));
        }

        $app       = Factory::getApplication();
        $input     = $app->getInput();
        $sessionId = $input->get('sessionId', '', 'string');
        $batch     = $input->get('batch', 0, 'int');
        $session   = $app->getSession();

        $batchQueries = $this->readImportSpool($sessionId, $batch);

        if ($batchQueries === []) {
            $this->sendJsonResponse(false, Text::_('JBS_IBM_SPOOL_MISSING'));
        }

        $db = Factory::getContainer()->get(DatabaseInterface::class);

        // For the first batch, drop Proclaim's own tables.
        //
        // ⚠️ This used to carry `$preserve = ['#__bsms_bible_verses']`, meaning
        // to keep downloaded bible data across a restore. It could not work.
        // The export wrote a `DROP TABLE IF EXISTS` for every table it dumped,
        // including that one, so skipping the drop here only deferred it by a
        // few statements — the backup's own SQL dropped and recreated the table
        // from the snapshot. The intent was right and the mechanism was not.
        //
        // getOwnObjects() excludes the whole shared scripture stack, which is
        // the library's to manage -- as it already is on uninstall. Nothing
        // here drops them, and every statement below is put through
        // Cwmrestore::classifyStatement(), so an older backup still carrying
        // those tables cannot reach them either.
        if ($batch === 0) {
            $objects = CwmdbHelper::getOwnObjects();

            foreach ($objects as $object) {
                $dropper = 'DROP TABLE IF EXISTS ' . $db->quoteName($object['name']);
                $db->setQuery($dropper);
                $db->execute();
            }
        }

        // Execute batch queries.
        //
        // A failure here is reported, not just logged. Batch 0 has already
        // dropped all of Proclaim's tables, so a restore that quietly gives up
        // partway leaves the site emptier than it found it -- and the caller
        // used to be told the batch succeeded regardless of how many
        // statements inside it had not.
        $executed = 0;
        $skipped  = 0;
        $errors   = [];

        foreach ($batchQueries as $query) {
            $query = trim($query);

            if ($query === '' || $query[0] === '#') {
                continue;
            }

            $verdict = Cwmrestore::classifyStatement($query);

            if ($verdict !== Cwmrestore::STATEMENT_ALLOWED) {
                $skipped++;

                if ($verdict === Cwmrestore::STATEMENT_REJECTED) {
                    Log::add(
                        'Import skipped a statement targeting a table outside Proclaim: ' . substr($query, 0, 120),
                        Log::WARNING,
                        'com_proclaim'
                    );
                }

                continue;
            }

            try {
                $db->setQuery($query);
                $db->execute();
                $executed++;
            } catch (\Exception $e) {
                $errors[] = [
                    'statement' => substr(preg_replace('/\s+/', ' ', $query) ?? '', 0, 160),
                    'error'     => $e->getMessage(),
                ];

                Log::add('Import query error: ' . $e->getMessage(), Log::ERROR, 'com_proclaim');
            }
        }

        $this->sendJsonResponse(true, '', [
            'batch'     => $batch,
            'processed' => \count($batchQueries),
            'executed'  => $executed,
            'skipped'   => $skipped,
            'failed'    => \count($errors),
            'errors'    => $errors,
        ]);
    }

    /**
     * Run a single post-restore data fix step via AJAX.
     *
     * Called sequentially by the JS after batch import completes.
     * Each step is independent — failure of one does not block others.
     *
     * @return void
     *
     * @throws \Exception
     * @since 10.2.0
     */
    public function postRestoreStepXHR(): void
    {
        $this->registerFatalErrorShutdownHandler();

        try {
            if (!Session::checkToken('get') && !Session::checkToken()) {
                $this->sendJsonResponse(false, Text::_('JINVALID_TOKEN'));
            }

            $app  = Factory::getApplication();
            $step = $app->getInput()->getInt('step', -1);

            // Give each step up to 5 minutes
            if (\function_exists('set_time_limit')) {
                set_time_limit(300);
            }

            $labels = [
                'Fixing teacher aliases',
                'Populating study-teacher links',
                'Migrating scripture references',
                'Seeding Bible translations',
                'Fixing media file legacy paths',
                'Migrating template defaults',
            ];

            $totalSteps = \count($labels);

            if ($step < 0 || $step >= $totalSteps) {
                $this->sendJsonResponse(false, 'Invalid post-restore step: ' . $step);
            }

            match ($step) {
                0 => CwmmigrationHelper::fixTeacherAliases(),
                1 => CwmmigrationHelper::populateStudyTeachers(),
                2 => CwmscriptureMigration::migrate(),
                3 => CwmmigrationHelper::seedBibleTranslations(),
                4 => CwmmigrationHelper::fixMediafileLegacyPaths(),
                5 => (new CwmtemplatemigrationHelper())->migrateAll(),
            };

            Log::add('Post-restore step ' . $step . ' completed: ' . $labels[$step], Log::INFO, 'com_proclaim');

            $this->sendJsonResponse(true, '', [
                'step'       => $step,
                'label'      => $labels[$step],
                'totalSteps' => $totalSteps,
            ]);
        } catch (\Exception $e) {
            $this->sendJsonResponse(false, 'Post-restore step error: ' . $e->getMessage());
        }
    }

    /**
     * Finalize import-fix assets and ownership
     *
     * @return void
     *
     * @throws \Exception
     * @since 10.1.0
     */
    public function finalizeImportXHR(): void
    {
        // Try to increase the memory limit (best-effort may fail on shared hosting)
        $currentLimit = $this->getMemoryLimitBytes();
        $targetLimit  = 512 * 1024 * 1024; // 512M

        if ($currentLimit > 0 && $currentLimit < $targetLimit) {
            // Try progressive increases - some hosts allow modest increases but not large ones
            foreach (['256M', '384M', '512M'] as $tryLimit) {
                @ini_set('memory_limit', $tryLimit);
            }
        }

        // Suppress error display and capture any output
        $previousErrorReporting = error_reporting(E_ALL);
        $previousDisplayErrors  = \ini_get('display_errors');
        ini_set('display_errors', '0');
        ob_start();

        $this->registerFatalErrorShutdownHandler();

        try {
            // Check for request forgeries
            if (!Session::checkToken('get') && !Session::checkToken()) {
                $this->sendJsonResponse(false, Text::_('JINVALID_TOKEN'));
            }

            $app           = Factory::getApplication();
            $input         = $app->getInput();
            $sessionId     = $input->get('sessionId', '', 'string');
            $skipAssetFix  = $input->get('skipAssetFix', '0', 'string') === '1';
            $dataFixesRun  = $input->get('dataFixesRun', '0', 'string') === '1';
            $session       = $app->getSession();

            // Retrieve and clean up the import file path before clearing session
            $importFilePath = $session->get('proclaim_import_' . $sessionId, '', 'CWM');

            // Clean up session data
            $session->set('proclaim_import_' . $sessionId, '', 'CWM');
            $session->set('proclaim_import_count_' . $sessionId, '', 'CWM');

            // And the statement spool this import wrote to disk.
            $spoolPath = $this->importSpoolPath($sessionId);

            if (is_file($spoolPath)) {
                File::delete($spoolPath);
            }

            // Reset schema version and run migrations so tables/columns added
            // after the backup was created get applied (e.g. bible_translations).
            $schemaFixed = $this->fixSchemaAfterRestore();

            // Run post-restore data fixes unless already run via postRestoreStepXHR
            if (!$dataFixesRun) {
                $this->runPostRestoreDataFixes();
            }

            // Correct AUTO_INCREMENT counters that may be stale from backup
            $autoIncrementFixes = Cwmrestore::correctAutoIncrements();

            // Fix assets using the centralised Cwmassets engine (unless skipped for testing)
            if (!$skipAssetFix) {
                Cwmassets::fixAllAssets();
            } else {
                Log::add('Asset fix skipped (testing mode)', Log::INFO, 'com_proclaim');
            }

            // Recreate templatecode PHP files from database records
            $templatecodesCreated = $this->recreateTemplatecodeFiles();

            // Verify restore integrity
            $integrity = Cwmrestore::verifyRestoreIntegrity();
            Log::add(
                \sprintf(
                    'Restore verification: %d tables, %d tasks, config %s',
                    $integrity['tables'],
                    $integrity['tasks'],
                    $integrity['config'] ? 'OK' : 'missing'
                ),
                Log::INFO,
                'com_proclaim'
            );

            // Clean up tmp files left by the import
            $this->cleanupImportTmpFiles($importFilePath);

            // What the restore could not do for the user. A 9.x backup arrives
            // with every server typed `legacy`, and the restore has no business
            // re-pointing thousands of media rows without being asked -- but it
            // should not report itself finished without saying so either.
            $pendingMigration = CwmserverMigrationHelper::countPendingMigration();

            $this->sendJsonResponse(true, Text::_('JBS_CMN_OPERATION_SUCCESSFUL'), [
                'templatecodes_created' => $templatecodesCreated,
                'tables_restored'       => $integrity['tables'],
                'tasks_restored'        => $integrity['tasks'],
                'config_restored'       => $integrity['config'],
                'auto_increment_fixes'  => $autoIncrementFixes,
                'pending_migration'     => $pendingMigration,
            ]);
        } catch (\Exception $e) {
            $this->sendJsonResponse(false, 'Import finalize error: ' . $e->getMessage());
        }
    }

    /**
     * Reset the schema version and run Joomla's DatabaseModel::fix() so that
     * SQL update files created after the backup run against the restored data.
     *
     * The restore replaces all bsms_* tables with backup data, but #__schemas
     * (a Joomla core table) keeps the pre-restore version. Without a reset,
     * fix() thinks the schema is already current and skips creating tables
     * that were added after the backup (e.g. bible_translations).
     *
     * @return  bool  True if schema was repaired successfully
     *
     * @since   10.1.0
     */
    private function fixSchemaAfterRestore(): bool
    {
        $db = Factory::getContainer()->get(DatabaseInterface::class);

        // Find the Proclaim extension ID
        $query = $db->createQuery();
        $query->select($db->quoteName('extension_id'))
            ->from($db->quoteName('#__extensions'))
            ->where($db->quoteName('element') . ' = ' . $db->quote('com_proclaim'));
        $db->setQuery($query);
        $cid = (int) $db->loadResult();

        if (!$cid) {
            Log::add('Cannot fix schema: com_proclaim not found in extensions', Log::WARNING, 'com_proclaim');

            return false;
        }

        // Reset #__schemas to force all update files to re-run
        $query = $db->createQuery();
        $query->delete($db->quoteName('#__schemas'))
            ->where($db->quoteName('extension_id') . ' = ' . $cid);
        $db->setQuery($query);
        $db->execute();

        $query = $db->createQuery();
        $query->insert($db->quoteName('#__schemas'))
            ->columns([$db->quoteName('extension_id'), $db->quoteName('version_id')])
            ->values($cid . ', ' . $db->quote('0.0.0'));
        $db->setQuery($query);
        $db->execute();

        // Run Joomla's schema fixer — processes all SQL update files in order
        $databaseModel = new DatabaseModel();
        $databaseModel->fix([$cid]);

        Log::add('Schema version reset and migrations re-applied after restore', Log::INFO, 'com_proclaim');

        return true;
    }

