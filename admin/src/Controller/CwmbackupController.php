    /**
     * Where an import's statements are spooled between requests.
     *
     * @param   string  $sessionId  The import's session id
     *
     * @return  string  Absolute path
     *
     * @throws  \Exception
     * @since   __DEPLOY_VERSION__
     */
    private function importSpoolPath(string $sessionId): string
    {
        $tmp = Factory::getApplication()->get('tmp_path', JPATH_ROOT . '/tmp');

        // The id is generated by prepareImportXHR/uploadImportFileXHR as an md5,
        // but it arrives from the request, so it never reaches the filesystem
        // unsanitised.
        return Path::clean($tmp . '/proclaim_import_' . preg_replace('/[^a-f0-9]/i', '', $sessionId) . '.jsonl');
    }

    /**
     * Delete spools left by imports that never finished.
     *
     * finalizeImportXHR() removes the spool for an import that runs to the end.
     * One that does not -- the browser closed, a request timed out, the user
     * walked away -- leaves a file the size of the dump behind, and nothing
     * else would ever come back for it. A 15 MB dump spools to 16 MB, so a few
     * abandoned attempts are worth noticing.
     *
     * Anything still present after a day is not part of a live import: batches
     * follow each other in seconds.
     *
     * @return  void
     *
     * @throws  \Exception
     * @since   __DEPLOY_VERSION__
     */
    private function sweepStaleSpools(): void
    {
        $tmp = Factory::getApplication()->get('tmp_path', JPATH_ROOT . '/tmp');
        $old = time() - 86400;

        foreach ((array) glob(Path::clean($tmp . '/proclaim_import_*.jsonl')) as $path) {
            if (!\is_string($path) || !is_file($path)) {
                continue;
            }

            if (filemtime($path) < $old) {
                File::delete($path);

                Log::add('Removed an abandoned import spool: ' . basename($path), Log::INFO, 'com_proclaim');
            }
        }
    }

    /**
     * Read one batch of statements back off the spool.
     *
     * Only the lines this batch needs are decoded, so a request costs the same
     * whether the dump held 200 statements or 200,000.
     *
     * @param   string  $sessionId  The import's session id
     * @param   int     $batch      Zero-based batch number
     *
     * @return  string[]  The statements, or an empty array if the spool is gone
     *
     * @throws  \Exception
     * @since   __DEPLOY_VERSION__
     */
    private function readImportSpool(string $sessionId, int $batch): array
    {
        $path = $this->importSpoolPath($sessionId);

        if (!is_file($path)) {
            return [];
        }

        $handle = fopen($path, 'rb');

        if ($handle === false) {
            return [];
        }

        $first   = $batch * self::IMPORT_BATCH_SIZE;
        $last    = $first + self::IMPORT_BATCH_SIZE;
        $line    = 0;
        $queries = [];

        while (($raw = fgets($handle)) !== false) {
            if ($line >= $first && $line < $last) {
                try {
                    $decoded = json_decode($raw, true, 512, JSON_THROW_ON_ERROR);
                } catch (\JsonException $e) {
                    // A truncated spool line means the statement is unrecoverable.
                    // Surfacing it beats running the rest and calling it a success.
                    Log::add(
                        'Import spool line ' . $line . ' could not be decoded: ' . $e->getMessage(),
                        Log::ERROR,
                        'com_proclaim'
                    );

                    $decoded = null;
                }

                if (\is_string($decoded)) {
                    $queries[] = $decoded;
                }
            }

            $line++;

            if ($line >= $last) {
                break;
            }
        }

        fclose($handle);

        return $queries;
    }

    /**
     * Get a list of tables for AJAX export
     *
     * @return void
     *
     * @throws \Exception
     * @since 10.1.0
     */
    public function getExportTablesXHR(): void
    {
        // Check for request forgeries
        if (!Session::checkToken('get') && !Session::checkToken()) {
            $this->sendJsonResponse(false, Text::_('JINVALID_TOKEN'));
        }

        $app    = Factory::getApplication();
        $config = $app->getConfig();

        // Create a unique export ID for this session
        $exportId = md5(uniqid((string) mt_rand(), true));
        $tmpPath  = $config->get('tmp_path') . '/proclaim_export_' . $exportId . '.sql';

        // Initialize an empty file
        file_put_contents($tmpPath, '');

        $tables     = CwmdbHelper::getOwnObjects();
        $tableNames = array_column($tables, 'name');

        // Add virtual "tables" for component config, scheduled tasks, and
        // per-record/component-level asset permissions. Virtual tables are
        // chunk-exempt and always dumped in one pass.
        $tableNames[] = '_component_config';
        $tableNames[] = '_scheduled_tasks';
        $tableNames[] = '_proclaim_assets';

        // Build table info with row counts for chunked export
        $backup    = new Cwmbackup();
        $tableInfo = [];

        foreach ($tableNames as $name) {
            $rows = 0;

            if (!str_starts_with($name, '_')) {
                try {
                    $rows = $backup->getTableRowCount($name);
                } catch (\Exception $e) {
                    Log::add('Failed to count rows for ' . $name . ': ' . $e->getMessage(), Log::WARNING, 'com_proclaim');
                }
            }

            $tableInfo[] = ['name' => $name, 'rows' => $rows];
        }

        // Return the export ID so it can be passed to later calls
        $this->sendJsonResponse(true, '', ['tables' => $tableInfo, 'exportId' => $exportId]);
    }

    /**
     * Export a single table via AJAX
     *
     * @return void
     *
     * @throws \Exception
     * @since 10.1.0
     */
    public function exportTableXHR(): void
    {
        // Check for request forgeries
        if (!Session::checkToken('get') && !Session::checkToken()) {
            $this->sendJsonResponse(false, Text::_('JINVALID_TOKEN'));
        }

        $app      = Factory::getApplication();
        $input    = $app->getInput();
        $config   = $app->getConfig();
        $table    = $input->get('table', '', 'string');
        $exportId = $input->get('exportId', '', 'string');
        $offset   = $input->getInt('offset', -1);
        $limit    = $input->getInt('limit', 0);

        if (empty($table)) {
            $this->sendJsonResponse(false, 'No table specified');
        }

        if (empty($exportId)) {
            $this->sendJsonResponse(false, 'No export ID specified');
        }

        // Build the temp file path from the export ID
        $tmpPath = $config->get('tmp_path') . '/proclaim_export_' . $exportId . '.sql';

        if (!is_file($tmpPath)) {
            $this->sendJsonResponse(false, 'Export file not found. Please start again.');
        }

        $backup = new Cwmbackup();

        // Chunked export: offset >= 0 and limit > 0 triggers row-range mode
        if ($offset >= 0 && $limit > 0 && !str_starts_with($table, '_')) {
            $tableData = '';

            // First chunk includes DDL (DROP + CREATE)
            if ($offset === 0) {
                $tableData .= $backup->getExportTableStructure($table);
            }

            $tableData .= $backup->getExportTableRows($table, $offset, $limit);

            // Add separator after the last chunk
            $rowCount = $backup->getTableRowCount($table);

            if ($offset + $limit >= $rowCount) {
                $tableData .= "\n-- --------------------------------------------------------\n\n";
            }
        } else {
            // Full export (small tables or virtual tables)
            $tableData = $backup->getExportTableData($table);
        }

        // Append to temp file
        if (file_put_contents($tmpPath, $tableData, FILE_APPEND) === false) {
            $this->sendJsonResponse(false, 'Failed to write export data');
        }

        $this->sendJsonResponse(true, '', ['table' => $table, 'size' => \strlen($tableData)]);
    }

    /**
     * Finalize export and create a download file
     *
     * @return void
     *
     * @throws \Exception
     * @since 10.1.0
     */
    public function finalizeExportXHR(): void
    {
        $this->registerFatalErrorShutdownHandler();

        try {
            // Check for request forgeries
            if (!Session::checkToken('get') && !Session::checkToken()) {
                $this->sendJsonResponse(false, Text::_('JINVALID_TOKEN'));
            }

            $app      = Factory::getApplication();
            $input    = $app->getInput();
            $mode     = $input->get('mode', 'download', 'string');
            $exportId = $input->get('exportId', '', 'string');
            $session  = $app->getSession();
            $config   = $app->getConfig();

            if (empty($exportId)) {
                $this->sendJsonResponse(false, 'No export ID specified');
            }

            // Build the temp file path from the export ID
            $tmpExportPath = $config->get('tmp_path') . '/proclaim_export_' . $exportId . '.sql';

            if (!is_file($tmpExportPath)) {
                $this->sendJsonResponse(false, 'Export file not found. Please start again.');
            }

            // Generate filename using standardized method
            $filename = Cwmbackup::generateBackupFilename();

            // Check if compression is requested (default: yes)
            $compress = $input->getInt('jbs_compress', 1);

            if ($mode === 'save') {
                // Save to back up folder
                $backupDir = JPATH_SITE . '/media/com_proclaim/backup/';

                if (!is_dir($backupDir)) {
                    Folder::create($backupDir);
                }

                $path = $backupDir . $filename;

                // Move the temp file to backup location
                if (!rename($tmpExportPath, $path)) {
                    // Fallback to copy + delete
                    if (!copy($tmpExportPath, $path)) {
                        $this->sendJsonResponse(false, 'Failed to write backup file');
                    }
                    File::delete($tmpExportPath);
                }

                // Compress the file if requested
                if ($compress) {
                    $zipPath  = $this->compressBackupFile($path);
                    $path     = $zipPath;
                    $filename = basename($zipPath);
                }

                // Clean up old backups
                $backup = new Cwmbackup();
                $backup->updatefiles(Cwmparams::getAdmin()->params);

                $this->sendJsonResponse(true, '', ['filename' => $filename, 'path' => $path]);
            } else {
                // Rename temp file for download
                $downloadPath = $config->get('tmp_path') . '/' . $filename;

                if (!rename($tmpExportPath, $downloadPath)) {
                    // Fallback to copy + delete
                    if (!copy($tmpExportPath, $downloadPath)) {
                        $this->sendJsonResponse(false, 'Failed to prepare download file');
                    }
                    File::delete($tmpExportPath);
                }

                // Compress the file if requested
                if ($compress) {
                    $zipPath      = $this->compressBackupFile($downloadPath);
                    $downloadPath = $zipPath;
                    $filename     = basename($zipPath);
                }

                // Store path in session for download (needed for the download redirect)
                $session->set('proclaim_download_file', $downloadPath, 'CWM');

                // Return URL for download
                $downloadUrl = Route::_('index.php?option=com_proclaim&task=cwmbackup.downloadExportXHR&' . Session::getFormToken() . '=1', false);

                $this->sendJsonResponse(true, '', ['filename' => $filename, 'downloadUrl' => $downloadUrl]);
            }
        } catch (\Exception $e) {
            $this->sendJsonResponse(false, 'Export error: ' . $e->getMessage());
        }
    }

    /**
     * Download the exported file
     *
     * @return void
     *
     * @throws \Exception
     * @since 10.1.0
     */
    public function downloadExportXHR(): void
    {
        // Check for request forgeries
        if (!Session::checkToken('get') && !Session::checkToken()) {
            throw new \RuntimeException(Text::_('JINVALID_TOKEN'));
        }

        $app     = Factory::getApplication();
        $session = $app->getSession();

        $filePath = $session->get('proclaim_download_file', '', 'CWM');

        if (empty($filePath) || !is_file($filePath)) {
            throw new \RuntimeException('Download file not found');
        }

        // Clear session
        $session->set('proclaim_download_file', '', 'CWM');

        // Determine MIME type based on file extension
        $mimeType = str_ends_with(strtolower($filePath), '.zip') ? 'application/zip' : 'text/x-sql';

        // Output file
        $backup = new Cwmbackup();
        $backup->outputFile($filePath, basename($filePath), $mimeType);

        // Clean up
        File::delete($filePath);

        $app->close();
    }

