-- A template could have `series_detail_sort` saved as `booknumber`, which
-- Cwmserieslist puts straight into ORDER BY. The column is gone as of this
-- file, so the saved value has to go with it or the series detail page fatals.

UPDATE `#__bsms_templates`
SET `params` = REPLACE(`params`, '"series_detail_sort":"booknumber"', '"series_detail_sort":"studydate"')
WHERE `params` LIKE '%"series_detail_sort":"booknumber"%';
